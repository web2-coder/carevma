<?php

namespace App\Services;

use App\Models\Attendance;
use App\Models\Client;
use App\Models\ClientEmployeeRate;
use App\Models\EmployeeSalary;
use App\Models\Invoice;
use App\Models\InvoiceAdjustment;
use Carbon\Carbon;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

class InvoiceGenerator
{
    public function __construct(
        private TrustedTimeService $clock,
        private ClientTimezoneService $timezones,
    ) {
    }

    /**
     * Generate a single Doctor/Client invoice containing one salary row per VA.
     *
     * Scope rules:
     * - employeeIds === null: include every assigned/billable VA with completed,
     *   unbilled attendance in the requested period.
     * - employeeIds provided: include only those selected VAs.
     *
     * First-month rule is still enforced per VA. Each salary row starts from that
     * VA's own first actual check-in date (or the requested start date when later),
     * so a later-starting VA never shows pre-check-in OFF/ABSENT days in the PDF.
     *
     * @param int[]|null $employeeIds
     */
    public function generate(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated = false, ?array $employeeIds = null): ?Invoice
    {
        // Doctor-level idempotency: a single Doctor/end-period must never keep
        // multiple editable draft invoices. Consolidate any legacy split drafts
        // before deciding what attendance still needs to be added. Final/sent/paid
        // invoices are deliberately excluded from this cleanup.
        $existingDraft = $this->consolidateDraftInvoices($client, $periodEnd, $autoGenerated);

        [$periodStartUtc, $periodEndUtc] = $this->timezones->utcBoundsForLocalDates($periodStart, $periodEnd, $client);

        $attendanceQuery = Attendance::query()
            ->where('client_id', $client->id)
            ->whereBetween('clock_in', [$periodStartUtc, $periodEndUtc])
            ->whereNotNull('clock_out');

        if ($employeeIds !== null) {
            $attendanceQuery->whereIn('employee_id', $employeeIds);
        }

        // Existing non-void invoices only cover the VAs actually present on them.
        // This allows another VA for the same Doctor/date range to be billed later
        // without creating duplicate billing for already invoiced attendance.
        $coveredPeriodsQuery = Invoice::query()->where('client_id', $client->id);
        if (Schema::hasColumn('invoices', 'status')) {
            $coveredPeriodsQuery->where(function ($query) {
                $query->whereNull('status')->orWhere('status', '!=', 'void');
            });
        }

        $coveredPeriods = $coveredPeriodsQuery
            ->whereDate('period_start', '<=', $periodEnd)
            ->whereDate('period_end', '>=', $periodStart)
            ->with('salaries:id,invoice_id,employee_id')
            ->get(['id', 'period_start', 'period_end']);

        foreach ($coveredPeriods as $covered) {
            [$coveredStartUtc, $coveredEndUtc] = $this->timezones->utcBoundsForLocalDates(
                $covered->period_start->toDateString(),
                $covered->period_end->toDateString(),
                $client
            );
            $billedEmployeeIds = $covered->salaries->pluck('employee_id')->filter()->all();
            if (!$billedEmployeeIds) {
                continue;
            }

            $attendanceQuery->where(function ($query) use ($coveredStartUtc, $coveredEndUtc, $billedEmployeeIds) {
                $query->whereNotBetween('clock_in', [$coveredStartUtc, $coveredEndUtc])
                    ->orWhereNotIn('employee_id', $billedEmployeeIds);
            });
        }

        $attendanceByEmployee = $attendanceQuery->get()->groupBy('employee_id');
        if ($attendanceByEmployee->isEmpty()) {
            // Re-generating the same Doctor/period is idempotent. If a draft
            // already contains the billable VAs, return that single invoice
            // instead of creating another record or reporting a false duplicate.
            return $existingDraft?->fresh(['client', 'salaries.employee']);
        }

        // Keep Doctor assignment/date scoping unchanged.
        $scheduleByEmployee = collect();
        if (Schema::hasTable('employee_client_schedules')) {
            $scheduleQuery = DB::table('employee_client_schedules')
                ->where('client_id', $client->id)
                ->whereIn('employee_id', $attendanceByEmployee->keys());
            if (Schema::hasColumn('employee_client_schedules', 'enabled')) {
                $scheduleQuery->where('enabled', true);
            }
            $scheduleByEmployee = $scheduleQuery->get()->groupBy('employee_id');
        }

        $attendanceByEmployee = $attendanceByEmployee->map(function ($records, $employeeId) use ($scheduleByEmployee, $client) {
            $schedules = $scheduleByEmployee->get($employeeId, collect());
            if ($schedules->isEmpty()) {
                return $records->values();
            }

            return $records->filter(function (Attendance $record) use ($schedules, $client) {
                if (!$record->clock_in) {
                    return false;
                }

                $localDate = $this->timezones->localDate($record->clock_in, $client);
                $dayName = Carbon::parse($localDate)->format('l');

                return $schedules->contains(function ($schedule) use ($localDate, $dayName) {
                    if (!empty($schedule->schedule_date)) {
                        return Carbon::parse($schedule->schedule_date)->toDateString() === $localDate;
                    }

                    return strcasecmp((string) ($schedule->weekday ?? ''), $dayName) === 0;
                });
            })->values();
        })->filter(fn ($records) => $records->isNotEmpty());

        if ($attendanceByEmployee->isEmpty()) {
            return $existingDraft?->fresh(['client', 'salaries.employee']);
        }

        // Build per-VA billable payloads first so every VA keeps its own first-check-in cutoff.
        $vaPayloads = collect();
        foreach ($attendanceByEmployee as $employeeId => $records) {
            $firstCheckIn = Attendance::query()
                ->where('client_id', $client->id)
                ->where('employee_id', $employeeId)
                ->whereNotNull('clock_in')
                ->orderBy('clock_in')
                ->value('clock_in');

            if (!$firstCheckIn) {
                continue;
            }

            $firstCheckInDate = $this->timezones->localDate($firstCheckIn, $client);
            $effectiveStart = Carbon::parse($periodStart)->startOfDay();
            $firstDate = Carbon::parse($firstCheckInDate)->startOfDay();
            if ($firstDate->gt($effectiveStart)) {
                $effectiveStart = $firstDate;
            }

            $effectiveEnd = Carbon::parse($periodEnd)->endOfDay();
            if ($effectiveStart->gt($effectiveEnd)) {
                continue;
            }

            $effectiveRecords = $records->filter(function (Attendance $record) use ($client, $effectiveStart, $effectiveEnd) {
                if (!$record->clock_in) {
                    return false;
                }
                $date = Carbon::parse($this->timezones->localDate($record->clock_in, $client))->startOfDay();
                return !$date->lt($effectiveStart) && !$date->gt($effectiveEnd);
            })->values();

            if ($effectiveRecords->isEmpty()) {
                continue;
            }

            $vaPayloads->push([
                'employee_id' => (int) $employeeId,
                'records' => $effectiveRecords,
                'period_start' => $effectiveStart->toDateString(),
                'period_end' => Carbon::parse($periodEnd)->toDateString(),
            ]);
        }

        if ($vaPayloads->isEmpty()) {
            return $existingDraft?->fresh(['client', 'salaries.employee']);
        }

        return $this->createCombinedInvoice($client, $vaPayloads, $periodEnd, $autoGenerated, $existingDraft);
    }

    /**
     * Backward-compatible helper for callers that still expect a collection.
     * It now returns either an empty collection or a one-item collection because
     * one Doctor/date-range run creates one invoice containing all scoped VAs.
     *
     * @param int[]|null $employeeIds
     * @return Collection<int, Invoice>
     */
    public function generateMany(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated = false, ?array $employeeIds = null): Collection
    {
        $invoice = $this->generate($client, $periodStart, $periodEnd, $autoGenerated, $employeeIds);
        return $invoice ? collect([$invoice]) : collect();
    }

    private function createCombinedInvoice(Client $client, Collection $vaPayloads, string $periodEnd, bool $autoGenerated, ?Invoice $existingDraft = null): Invoice
    {
        return DB::transaction(function () use ($client, $vaPayloads, $periodEnd, $autoGenerated, $existingDraft) {
            $invoicePeriodStart = $vaPayloads->min('period_start');
            $billingCycleMonth = Carbon::parse($periodEnd)->startOfMonth()->toDateString();

            $invoice = $existingDraft
                ? Invoice::query()->whereKey($existingDraft->id)->lockForUpdate()->first()
                : null;

            if (!$invoice) {
                $invoiceData = [
                    'client_id' => $client->id,
                    'invoice_number' => $this->nextNumber($client),
                    // Header starts at the earliest effective VA start. Each VA salary row
                    // still carries its own period_start for attendance/PDF rendering.
                    'period_start' => $invoicePeriodStart,
                    'period_end' => Carbon::parse($periodEnd)->toDateString(),
                    'total_hours' => 0,
                    'total_amount' => 0,
                ];
                if (Schema::hasColumn('invoices', 'billing_cycle_month')) $invoiceData['billing_cycle_month'] = $billingCycleMonth;
                if (Schema::hasColumn('invoices', 'status')) $invoiceData['status'] = 'draft';
                if (Schema::hasColumn('invoices', 'auto_generated')) $invoiceData['auto_generated'] = $autoGenerated;
                if (Schema::hasColumn('invoices', 'generated_at')) $invoiceData['generated_at'] = $this->clock->now('UTC');

                $invoice = Invoice::create($invoiceData);
            } else {
                $existingStart = Carbon::parse($invoice->period_start)->toDateString();
                if ($invoicePeriodStart < $existingStart) {
                    $invoice->period_start = $invoicePeriodStart;
                }
                if (Schema::hasColumn('invoices', 'billing_cycle_month')) {
                    $invoice->billing_cycle_month = $billingCycleMonth;
                }
                $invoice->save();
            }

            $existingEmployeeIds = $invoice->salaries()->pluck('employee_id')->map(fn ($id) => (int) $id)->all();

            foreach ($vaPayloads as $payload) {
                $employeeId = (int) $payload['employee_id'];
                if (in_array($employeeId, $existingEmployeeIds, true)) {
                    continue;
                }
                /** @var Collection<int, Attendance> $records */
                $records = $payload['records'];

                // Existing payment rules remain unchanged: regular payable + approved OT.
                $regularMinutes = (int) $records->sum('total_minutes');
                $approvedOvertime = Schema::hasColumn('attendances', 'approved_overtime_minutes')
                    ? (int) $records->sum(function (Attendance $record) {
                        if (($record->overtime_status ?? 'none') !== 'approved') {
                            return 0;
                        }
                        return min(
                            max(0, (int) ($record->approved_overtime_minutes ?? 0)),
                            max(0, (int) ($record->overtime ?? 0))
                        );
                    })
                    : 0;

                $rate = ClientEmployeeRate::where([
                    'client_id' => $client->id,
                    'employee_id' => $employeeId,
                ])->value('per_hour_rate') ?? $client->per_hour_charges ?? 0;

                $overtimePayment = $records->sum(function (Attendance $record) use ($rate) {
                    if (($record->overtime_status ?? 'none') !== 'approved') {
                        return 0;
                    }
                    $minutes = min(
                        max(0, (int) ($record->approved_overtime_minutes ?? 0)),
                        max(0, (int) ($record->overtime ?? 0))
                    );
                    return $record->overtime_amount !== null
                        ? (float) $record->overtime_amount
                        : ($minutes / 60 * $rate);
                });

                $actualWorkedMinutes = (int) $records->sum(fn (Attendance $record) => $this->actualWorkedMinutes($record));
                $actualWorkedHours = $actualWorkedMinutes / 60;
                $amount = ($regularMinutes / 60 * $rate) + $overtimePayment;

                $salaryData = [
                    'employee_id' => $employeeId,
                    'client_id' => $client->id,
                    'total_hours' => round($actualWorkedHours, 2),
                    'salary_amount' => round($amount, 2),
                    // Critical: per-VA first-check-in cutoff is stored here.
                    'period_start' => $payload['period_start'],
                    'period_end' => $payload['period_end'],
                ];
                if (Schema::hasColumn('employee_salaries', 'invoice_id')) $salaryData['invoice_id'] = $invoice->id;
                if (Schema::hasColumn('employee_salaries', 'total_late')) $salaryData['total_late'] = (int) $records->sum('late_minutes');
                if (Schema::hasColumn('employee_salaries', 'total_overtime')) $salaryData['total_overtime'] = $approvedOvertime;

                EmployeeSalary::create($salaryData);
                $existingEmployeeIds[] = $employeeId;
            }

            // Always recompute from the complete combined invoice so reusing an
            // existing draft cannot lose or double-count previously added VAs.
            $salaryRows = $invoice->salaries()->get();
            $invoice->update([
                'period_start' => $salaryRows->min('period_start') ?: $invoice->period_start,
                'total_hours' => round((float) $salaryRows->sum('total_hours'), 2),
                'total_amount' => round((float) $salaryRows->sum('salary_amount'), 2),
            ]);

            return $invoice->fresh(['client', 'salaries.employee']);
        }, 3);
    }

    /**
     * Collapse legacy split draft invoices for the same Doctor/end-period into one
     * editable draft. Only draft/null-status invoices are touched; finalized history
     * is never mutated. Distinct VA salary rows and adjustments are preserved.
     */
    private function consolidateDraftInvoices(Client $client, string $periodEnd, bool $autoGenerated): ?Invoice
    {
        return DB::transaction(function () use ($client, $periodEnd, $autoGenerated) {
            $query = Invoice::query()
                ->where('client_id', $client->id)
                ->whereDate('period_end', Carbon::parse($periodEnd)->toDateString());

            if (Schema::hasColumn('invoices', 'status')) {
                $query->where(function ($q) {
                    $q->whereNull('status')->orWhere('status', 'draft');
                });
            }
            if (Schema::hasColumn('invoices', 'auto_generated')) {
                $query->where('auto_generated', $autoGenerated);
            }

            $drafts = $query->orderBy('id')->lockForUpdate()->get();
            if ($drafts->isEmpty()) {
                return null;
            }

            /** @var Invoice $master */
            $master = $drafts->shift();
            $masterEmployeeIds = $master->salaries()->pluck('employee_id')->map(fn ($id) => (int) $id)->all();

            foreach ($drafts as $duplicate) {
                foreach ($duplicate->salaries()->get() as $salary) {
                    $employeeId = (int) $salary->employee_id;
                    if (!in_array($employeeId, $masterEmployeeIds, true)) {
                        $salary->invoice_id = $master->id;
                        $salary->save();
                        $masterEmployeeIds[] = $employeeId;
                    } else {
                        // Same VA already exists on the master. Treat this as a
                        // duplicate draft line rather than double-billing it.
                        $salary->delete();
                    }
                }

                if (Schema::hasTable('invoice_adjustments')) {
                    InvoiceAdjustment::query()
                        ->where('invoice_id', $duplicate->id)
                        ->update(['invoice_id' => $master->id]);
                }

                $duplicate->delete();
            }

            $salaryRows = $master->salaries()->get();
            if ($salaryRows->isNotEmpty()) {
                $master->period_start = $salaryRows->min('period_start') ?: $master->period_start;
                $master->total_hours = round((float) $salaryRows->sum('total_hours'), 2);
                $master->total_amount = round((float) $salaryRows->sum('salary_amount'), 2);
                $master->save();
            }

            return $master->fresh(['salaries']);
        }, 3);
    }

    /**
     * Invoice Total Hours is the visible clock-in -> clock-out elapsed duration.
     * Breaks are intentionally NOT deducted here; they are shown separately and
     * continue to affect Payable Hours through the existing billing rules.
     * Snap to minute boundaries so 11:03 AM -> 11:10 AM displays as 7m even
     * when the stored timestamps contain hidden seconds.
     */
    private function actualWorkedMinutes(Attendance $record): int
    {
        if (!$record->clock_in || !$record->clock_out) {
            return 0;
        }

        $clockIn = Carbon::parse($record->clock_in)->startOfMinute();
        $clockOut = Carbon::parse($record->clock_out)->startOfMinute();
        if ($clockOut->lte($clockIn)) {
            return 0;
        }

        return max(0, (int) $clockIn->diffInMinutes($clockOut));
    }

    private function nextNumber(Client $client): string
    {
        do {
            $number = (string) random_int(1000000, 9999999);
        } while (Invoice::where('invoice_number', $number)->exists());

        return $number;
    }
}
