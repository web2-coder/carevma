<?php

namespace App\Services;

use App\Models\Attendance;
use App\Models\Client;
use App\Models\ClientEmployeeRate;
use App\Models\EmployeeSalary;
use App\Models\Invoice;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;

class InvoiceGenerator
{
    public function __construct(
        private TrustedTimeService $clock,
        private ClientTimezoneService $timezones,
    ) {
    }

    public function generate(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated = false): ?Invoice
    {
        $existing = Invoice::where('client_id', $client->id)
            ->where('period_start', $periodStart)
            ->where('period_end', $periodEnd)
            ->first();

        if ($existing) {
            return $existing;
        }

        [$periodStartUtc, $periodEndUtc] = $this->timezones->utcBoundsForLocalDates($periodStart, $periodEnd, $client);
        $attendanceQuery = Attendance::query()
            ->whereBetween('clock_in', [$periodStartUtc, $periodEndUtc])
            ->whereNotNull('clock_out');

        // A requested 25th -> next-month 26th cycle overlaps the adjacent calendar cycle.
        // Exclude dates already covered by an existing non-void invoice for this client so the
        // same attendance can never be billed twice.
        $coveredPeriods = Invoice::query()
            ->where('client_id', $client->id)
            ->where(function ($query) {
                $query->whereNull('status')->orWhere('status', '!=', 'void');
            })
            ->whereDate('period_start', '<=', $periodEnd)
            ->whereDate('period_end', '>=', $periodStart)
            ->get(['period_start', 'period_end']);

        foreach ($coveredPeriods as $covered) {
            [$coveredStartUtc, $coveredEndUtc] = $this->timezones->utcBoundsForLocalDates(
                $covered->period_start->toDateString(),
                $covered->period_end->toDateString(),
                $client
            );
            $attendanceQuery->whereNotBetween('clock_in', [$coveredStartUtc, $coveredEndUtc]);
        }

        if (Schema::hasColumn('attendances', 'client_id')) {
            $attendanceQuery->where('client_id', $client->id);
        } else {
            $employeeIds = DB::table('employee_client_schedules')
                ->where('client_id', $client->id)
                ->pluck('employee_id');
            $attendanceQuery->whereIn('employee_id', $employeeIds);
        }

        $attendance = $attendanceQuery->get()->groupBy('employee_id');
        if ($attendance->isEmpty()) {
            return null;
        }

        return DB::transaction(function () use ($attendance, $client, $periodStart, $periodEnd, $autoGenerated) {
            $invoice = Invoice::create([
                'client_id' => $client->id,
                'invoice_number' => $this->nextNumber($client),
                'period_start' => $periodStart,
                'period_end' => $periodEnd,
                'total_hours' => 0,
                'total_amount' => 0,
                'status' => 'draft',
                'auto_generated' => $autoGenerated,
                'generated_at' => $this->clock->now('UTC'),
            ]);

            $totalHours = 0;
            $totalAmount = 0;

            foreach ($attendance as $employeeId => $records) {
                $regularMinutes = (int) $records->sum('total_minutes');
                $approvedOvertime = Schema::hasColumn('attendances', 'approved_overtime_minutes')
                    ? (int) $records->sum('approved_overtime_minutes')
                    : 0;

                $rate = ClientEmployeeRate::where([
                    'client_id' => $client->id,
                    'employee_id' => $employeeId,
                ])->value('per_hour_rate') ?? $client->per_hour_charges ?? 0;

                $overtimePayment = $records->sum(function (Attendance $record) use ($rate) {
                    $minutes = (int) ($record->approved_overtime_minutes ?? 0);
                    return $record->overtime_amount !== null
                        ? (float) $record->overtime_amount
                        : ($minutes / 60 * $rate);
                });

                $hours = ($regularMinutes + $approvedOvertime) / 60;
                $amount = ($regularMinutes / 60 * $rate) + $overtimePayment;

                EmployeeSalary::create([
                    'employee_id' => $employeeId,
                    'client_id' => $client->id,
                    'invoice_id' => $invoice->id,
                    'total_hours' => round($hours, 2),
                    'total_late' => (int) $records->sum('late_minutes'),
                    'total_overtime' => $approvedOvertime,
                    'salary_amount' => round($amount, 2),
                    'period_start' => $periodStart,
                    'period_end' => $periodEnd,
                ]);

                $totalHours += $hours;
                $totalAmount += $amount;
            }

            $invoice->update([
                'total_hours' => round($totalHours, 2),
                'total_amount' => round($totalAmount, 2),
            ]);

            return $invoice->fresh(['client', 'salaries.employee']);
        });
    }

    private function nextNumber(Client $client): string
    {
        do {
            $number = 'INV-'.$this->timezones->now($client)->format('Ym').'-'.strtoupper(Str::random(6));
        } while (Invoice::where('invoice_number', $number)->exists());

        return $number;
    }
}
