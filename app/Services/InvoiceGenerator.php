<?php

namespace App\Services;

use App\Models\Attendance;
use App\Models\Client;
use App\Models\ClientEmployeeRate;
use App\Models\EmployeeSalary;
use App\Models\Invoice;
use Carbon\Carbon;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

class InvoiceGenerator
{
    public function __construct(
        private TrustedTimeService $clock,
        private ClientTimezoneService $timezones,
        private InvoiceAttendanceScope $attendanceScope,
    ) {
    }

    /**
     * Generate a single Doctor/Client invoice containing one salary row per VA.
     *
     * Scope rules:
     * - employeeIds === null: include every assigned/billable VA with completed,
     *   unbilled attendance in the requested period.
     * - employeeIds provided: include only those selected VAs.
     *
     * First-month rule is still enforced per VA. Each salary row starts from that
     * VA's own first actual check-in date (or the requested start date when later),
     * so a later-starting VA never shows pre-check-in OFF/ABSENT days in the PDF.
     *
     * @param int[]|null $employeeIds
     */
    public function generate(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated = false, ?array $employeeIds = null): ?Invoice
    {
        // Reuse one editable Doctor draft for the same cycle/mode so multiple VAs
        // are accumulated into one invoice/PDF. Historical invoices are never
        // merged or deleted automatically.
        $existingDraft = $this->findReusableDraftInvoice($client, $periodStart, $periodEnd, $autoGenerated);

        [$periodStartUtc, $periodEndUtc] = $this->timezones->utcBoundsForLocalDates($periodStart, $periodEnd, $client);

        // Invoice math only needs a small attendance subset. Avoid hydrating every
        // attendance column for large billing periods while keeping calculations identical.
        $attendanceColumns = [
            'id', 'employee_id', 'client_id', 'schedule_id', 'date', 'timezone_snapshot',
            'shift_start_snapshot', 'shift_end_snapshot', 'clock_in', 'clock_out',
            'total_minutes', 'overtime', 'late_minutes',
        ];
        foreach (['overtime_status', 'approved_overtime_minutes', 'overtime_amount'] as $column) {
            if (Schema::hasColumn('attendances', $column)) {
                $attendanceColumns[] = $column;
            }
        }

        $attendanceQuery = Attendance::query()
            ->select($attendanceColumns)
            ->where('client_id', $client->id)
            ->whereBetween('clock_in', [$periodStartUtc, $periodEndUtc])
            ->whereNotNull('clock_out');

        if ($employeeIds !== null) {
            $attendanceQuery->whereIn('employee_id', $employeeIds);
        }

        // Existing non-void invoices only cover the VAs actually present on them.
        // This allows another VA for the same Doctor/date range to be billed later
        // without creating duplicate billing for already invoiced attendance.
        $coveredPeriodsQuery = Invoice::query()->where('client_id', $client->id);
        if (Schema::hasColumn('invoices', 'status')) {
            $coveredPeriodsQuery->where(function ($query) {
                $query->whereNull('status')->orWhere('status', '!=', 'void');
            });
        }

        $coveredPeriodColumns = ['id', 'period_start', 'period_end'];
        $hasAutoGeneratedColumn = Schema::hasColumn('invoices', 'auto_generated');
        if ($hasAutoGeneratedColumn) {
            $coveredPeriodColumns[] = 'auto_generated';
        }

        $coveredPeriods = $coveredPeriodsQuery
            ->whereDate('period_start', '<=', $periodEnd)
            ->whereDate('period_end', '>=', $periodStart)
            ->with('salaries:id,invoice_id,employee_id')
            ->get($coveredPeriodColumns);

        // Automatic generation is assignment-safe: when a Doctor/VA already has
        // a manual invoice anywhere in this target billing period, skip that VA
        // completely for this automatic run. Manual generation keeps its existing
        // date-level unbilled-attendance behavior unchanged.
        if ($autoGenerated && $hasAutoGeneratedColumn) {
            $manuallyBilledEmployeeIds = $coveredPeriods
                ->filter(fn (Invoice $invoice) => !$invoice->auto_generated)
                ->flatMap(fn (Invoice $invoice) => $invoice->salaries->pluck('employee_id'))
                ->filter()
                ->map(fn ($id) => (int) $id)
                ->unique()
                ->values()
                ->all();

            if ($manuallyBilledEmployeeIds) {
                $attendanceQuery->whereNotIn('employee_id', $manuallyBilledEmployeeIds);
            }
        }

        foreach ($coveredPeriods as $covered) {
            [$coveredStartUtc, $coveredEndUtc] = $this->timezones->utcBoundsForLocalDates(
                $covered->period_start->toDateString(),
                $covered->period_end->toDateString(),
                $client
            );
            $billedEmployeeIds = $covered->salaries->pluck('employee_id')->filter()->all();
            if (!$billedEmployeeIds) {
                continue;
            }

            $attendanceQuery->where(function ($query) use ($coveredStartUtc, $coveredEndUtc, $billedEmployeeIds) {
                $query->whereNotBetween('clock_in', [$coveredStartUtc, $coveredEndUtc])
                    ->orWhereNotIn('employee_id', $billedEmployeeIds);
            });
        }

        $attendanceByEmployee = $attendanceQuery->get()->groupBy('employee_id');
        if ($attendanceByEmployee->isEmpty()) {
            return null;
        }

        $scheduleByEmployee = $this->attendanceScope->schedules($client, $attendanceByEmployee->keys());
        $attendanceByEmployee = $attendanceByEmployee->map(fn ($records, $employeeId) =>
            $this->attendanceScope->filter($records, $client, $scheduleByEmployee->get($employeeId, collect()))
        )->filter(fn ($records) => $records->isNotEmpty());

        if ($attendanceByEmployee->isEmpty()) {
            return null;
        }

        // First check-in must pass the same Doctor/VA assignment validation as the billed rows.
        $firstCheckIns = collect();
        foreach ($attendanceByEmployee->keys() as $employeeId) {
            $first = $this->attendanceScope->firstValidCheckIn(
                $client, (int) $employeeId, $scheduleByEmployee->get($employeeId, collect())
            );
            if ($first) $firstCheckIns->put($employeeId, $first);
        }

        // Build per-VA billable payloads first so every VA keeps its own first-check-in cutoff.
        $vaPayloads = collect();
        foreach ($attendanceByEmployee as $employeeId => $records) {
            $firstCheckIn = $firstCheckIns->get($employeeId);

            if (!$firstCheckIn) {
                continue;
            }

            $firstCheckInDate = $this->timezones->localDate($firstCheckIn, $client);
            $effectiveStart = Carbon::parse($periodStart)->startOfDay();
            $firstDate = Carbon::parse($firstCheckInDate)->startOfDay();
            if ($firstDate->gt($effectiveStart)) {
                $effectiveStart = $firstDate;
            }

            $effectiveEnd = Carbon::parse($periodEnd)->endOfDay();
            if ($effectiveStart->gt($effectiveEnd)) {
                continue;
            }

            $effectiveRecords = $records->filter(function (Attendance $record) use ($client, $effectiveStart, $effectiveEnd) {
                if (!$record->clock_in) {
                    return false;
                }
                $date = Carbon::parse($this->timezones->localDate($record->clock_in, $client))->startOfDay();
                return !$date->lt($effectiveStart) && !$date->gt($effectiveEnd);
            })->values();

            if ($effectiveRecords->isEmpty()) {
                continue;
            }

            $vaPayloads->push([
                'employee_id' => (int) $employeeId,
                'records' => $effectiveRecords,
                'period_start' => $effectiveStart->toDateString(),
                'period_end' => Carbon::parse($periodEnd)->toDateString(),
            ]);
        }

        if ($vaPayloads->isEmpty()) {
            return null;
        }

        return $this->createCombinedInvoice($client, $vaPayloads, $periodStart, $periodEnd, $autoGenerated, $existingDraft);
    }

    /**
     * Backward-compatible helper for callers that still expect a collection.
     * It now returns either an empty collection or a one-item collection because
     * one Doctor/date-range run creates one invoice containing all scoped VAs.
     *
     * @param int[]|null $employeeIds
     * @return Collection<int, Invoice>
     */
    public function generateMany(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated = false, ?array $employeeIds = null): Collection
    {
        $invoice = $this->generate($client, $periodStart, $periodEnd, $autoGenerated, $employeeIds);
        return $invoice ? collect([$invoice]) : collect();
    }

    private function createCombinedInvoice(
        Client $client,
        Collection $vaPayloads,
        string $requestedPeriodStart,
        string $requestedPeriodEnd,
        bool $autoGenerated,
        ?Invoice $existingDraft = null
    ): ?Invoice {
        // Rates are stable for this generation run. Fetch all scoped VA rates once
        // instead of querying client_employee_rates inside the per-VA loop.
        $rateByEmployee = ClientEmployeeRate::query()
            ->where('client_id', $client->id)
            ->whereIn('employee_id', $vaPayloads->pluck('employee_id')->all())
            ->pluck('per_hour_rate', 'employee_id');

        return DB::transaction(function () use (
            $client,
            $vaPayloads,
            $requestedPeriodStart,
            $requestedPeriodEnd,
            $autoGenerated,
            $existingDraft,
            $rateByEmployee
        ) {
            // Serialize invoice creation per Doctor. This preserves the hardening
            // protection against manual and automatic generation racing each other.
            Client::query()->whereKey($client->id)->lockForUpdate()->firstOrFail();

            // Reuse one editable draft for the same Doctor/cycle/mode so all VAs
            // land on one Doctor invoice and therefore one PDF. Never merge/delete
            // historical invoices automatically.
            $invoice = null;
            if ($existingDraft) {
                $invoice = Invoice::query()->whereKey($existingDraft->id)->lockForUpdate()->first();
            }
            if (!$invoice) {
                $invoiceQuery = Invoice::query()
                    ->where('client_id', $client->id)
                    ->whereDate('period_end', Carbon::parse($requestedPeriodEnd)->toDateString())
                    ->whereDate('period_start', '>=', Carbon::parse($requestedPeriodStart)->toDateString());

                if (Schema::hasColumn('invoices', 'status')) {
                    $invoiceQuery->where(function ($query) {
                        $query->whereNull('status')->orWhere('status', 'draft');
                    });
                }
                if (Schema::hasColumn('invoices', 'auto_generated')) {
                    $invoiceQuery->where('auto_generated', $autoGenerated);
                }

                $invoice = $invoiceQuery->orderBy('id')->lockForUpdate()->first();
            }

            $existingEmployeeIds = $invoice
                ? $invoice->salaries()->pluck('employee_id')->map(fn ($id) => (int) $id)->all()
                : [];

            // Final coverage re-check after the Doctor lock. This closes the race
            // where another request could invoice a VA after the initial eligibility
            // query but before this transaction starts.
            $eligiblePayloads = collect();
            foreach ($vaPayloads as $payload) {
                $employeeId = (int) $payload['employee_id'];

                if (in_array($employeeId, $existingEmployeeIds, true)) {
                    continue;
                }

                $coveredQuery = Invoice::query()
                    ->where('client_id', $client->id)
                    ->whereDate('period_start', '<=', $requestedPeriodEnd)
                    ->whereDate('period_end', '>=', $requestedPeriodStart)
                    ->whereHas('salaries', fn ($query) => $query->where('employee_id', $employeeId));

                if ($invoice) {
                    $coveredQuery->whereKeyNot($invoice->id);
                }
                if (Schema::hasColumn('invoices', 'status')) {
                    $coveredQuery->where(function ($query) {
                        $query->whereNull('status')->orWhere('status', '!=', 'void');
                    });
                }

                $coveredColumns = ['id', 'period_start', 'period_end'];
                $hasAutoGeneratedColumn = Schema::hasColumn('invoices', 'auto_generated');
                if ($hasAutoGeneratedColumn) {
                    $coveredColumns[] = 'auto_generated';
                }

                $covered = $coveredQuery->lockForUpdate()->get($coveredColumns);

                // Exact rule: if this Doctor/VA assignment already has a manual
                // invoice in the target cycle, automatic generation skips that VA.
                if ($autoGenerated && $hasAutoGeneratedColumn && $covered->contains(fn (Invoice $item) => !$item->auto_generated)) {
                    continue;
                }

                /** @var Collection<int, Attendance> $records */
                $records = collect($payload['records']);
                foreach ($covered as $coveredInvoice) {
                    [$coveredStartUtc, $coveredEndUtc] = $this->timezones->utcBoundsForLocalDates(
                        $coveredInvoice->period_start->toDateString(),
                        $coveredInvoice->period_end->toDateString(),
                        $client
                    );

                    $records = $records->reject(function (Attendance $record) use ($coveredStartUtc, $coveredEndUtc) {
                        if (!$record->clock_in) {
                            return true;
                        }

                        return Carbon::parse($record->clock_in)->betweenIncluded($coveredStartUtc, $coveredEndUtc);
                    })->values();
                }

                if ($records->isEmpty()) {
                    continue;
                }

                $firstRemainingLocalDate = $records
                    ->map(fn (Attendance $record) => $this->timezones->localDate($record->clock_in, $client))
                    ->filter()
                    ->min();

                $effectiveStart = max(
                    $payload['period_start'],
                    $firstRemainingLocalDate ?: $payload['period_start']
                );

                $eligiblePayloads->push([
                    'employee_id' => $employeeId,
                    'records' => $records,
                    'period_start' => $effectiveStart,
                    'period_end' => $payload['period_end'],
                ]);
            }

            if ($eligiblePayloads->isEmpty()) {
                return $invoice?->fresh(['client', 'salaries.employee']);
            }

            $invoicePeriodStart = $eligiblePayloads->min('period_start');
            $billingCycleMonth = Carbon::parse($requestedPeriodEnd)->startOfMonth()->toDateString();

            if (!$invoice) {
                $invoiceData = [
                    'client_id' => $client->id,
                    'invoice_number' => $this->nextNumber($client),
                    'period_start' => $invoicePeriodStart,
                    'period_end' => Carbon::parse($requestedPeriodEnd)->toDateString(),
                    'total_hours' => 0,
                    'total_amount' => 0,
                ];
                if (Schema::hasColumn('invoices', 'billing_cycle_month')) $invoiceData['billing_cycle_month'] = $billingCycleMonth;
                if (Schema::hasColumn('invoices', 'status')) $invoiceData['status'] = 'draft';
                if (Schema::hasColumn('invoices', 'auto_generated')) $invoiceData['auto_generated'] = $autoGenerated;
                if (Schema::hasColumn('invoices', 'generated_at')) $invoiceData['generated_at'] = $this->clock->now('UTC');

                $invoice = Invoice::create($invoiceData);
            } else {
                $existingStart = Carbon::parse($invoice->period_start)->toDateString();
                if ($invoicePeriodStart < $existingStart) {
                    $invoice->period_start = $invoicePeriodStart;
                }
                if (Schema::hasColumn('invoices', 'billing_cycle_month')) {
                    $invoice->billing_cycle_month = $billingCycleMonth;
                }
                $invoice->save();
            }

            foreach ($eligiblePayloads as $payload) {
                $employeeId = (int) $payload['employee_id'];
                /** @var Collection<int, Attendance> $records */
                $records = $payload['records'];

                $regularMinutes = (int) $records->sum('total_minutes');
                $approvedOvertime = Schema::hasColumn('attendances', 'approved_overtime_minutes')
                    ? (int) $records->sum(function (Attendance $record) {
                        if (($record->overtime_status ?? 'none') !== 'approved') {
                            return 0;
                        }
                        return min(
                            max(0, (int) ($record->approved_overtime_minutes ?? 0)),
                            max(0, (int) ($record->overtime ?? 0))
                        );
                    })
                    : 0;

                $rate = $rateByEmployee->get($employeeId) ?? $client->per_hour_charges ?? 0;

                $overtimePayment = $records->sum(function (Attendance $record) use ($rate) {
                    if (($record->overtime_status ?? 'none') !== 'approved') {
                        return 0;
                    }
                    $minutes = min(
                        max(0, (int) ($record->approved_overtime_minutes ?? 0)),
                        max(0, (int) ($record->overtime ?? 0))
                    );
                    return $record->overtime_amount !== null
                        ? (float) $record->overtime_amount
                        : ($minutes / 60 * $rate);
                });

                // Invoice hours must represent billable/payable time, matching the
                // amount calculation and PDF: regular payable minutes + approved OT only.
                // Raw clock-in -> clock-out elapsed time can include breaks or pending OT
                // and therefore must not be stored as invoice total_hours.
                $billableMinutes = $regularMinutes + $approvedOvertime;
                $billableHours = $billableMinutes / 60;
                $amount = ($regularMinutes / 60 * $rate) + $overtimePayment;

                $salaryData = [
                    'employee_id' => $employeeId,
                    'client_id' => $client->id,
                    'total_hours' => round($billableHours, 2),
                    'salary_amount' => round($amount, 2),
                    'period_start' => $payload['period_start'],
                    'period_end' => $payload['period_end'],
                ];
                if (Schema::hasColumn('employee_salaries', 'invoice_id')) $salaryData['invoice_id'] = $invoice->id;
                if (Schema::hasColumn('employee_salaries', 'total_late')) $salaryData['total_late'] = (int) $records->sum('late_minutes');
                if (Schema::hasColumn('employee_salaries', 'total_overtime')) $salaryData['total_overtime'] = $approvedOvertime;

                EmployeeSalary::create($salaryData);
            }

            // One Doctor invoice totals all included VA rows; InvoicePdfService
            // already renders every salary/VA section into the same PDF.
            $salaryRows = $invoice->salaries()->get();
            $invoice->update([
                'period_start' => $salaryRows->min('period_start') ?: $invoice->period_start,
                'total_hours' => round((float) $salaryRows->sum('total_hours'), 2),
                'total_amount' => round((float) $salaryRows->sum('salary_amount'), 2),
            ]);

            return $invoice->fresh(['client', 'salaries.employee']);
        }, 3);
    }

    /**
     * Return one reusable editable draft for this Doctor/cycle/mode without
     * deleting, merging, or rewriting any historical invoice records.
     */
    private function findReusableDraftInvoice(Client $client, string $periodStart, string $periodEnd, bool $autoGenerated): ?Invoice
    {
        $query = Invoice::query()
            ->where('client_id', $client->id)
            ->whereDate('period_end', Carbon::parse($periodEnd)->toDateString())
            // The stored start may be later than the requested start because of the
            // first-check-in clamp. It must never be earlier than a new custom range.
            ->whereDate('period_start', '>=', Carbon::parse($periodStart)->toDateString());

        if (Schema::hasColumn('invoices', 'status')) {
            $query->where(function ($q) {
                $q->whereNull('status')->orWhere('status', 'draft');
            });
        }
        if (Schema::hasColumn('invoices', 'auto_generated')) {
            $query->where('auto_generated', $autoGenerated);
        }

        return $query->orderBy('id')->first();
    }

    private function nextNumber(Client $client): string
    {
        do {
            $number = (string) random_int(1000000, 9999999);
        } while (Invoice::where('invoice_number', $number)->exists());

        return $number;
    }
}
